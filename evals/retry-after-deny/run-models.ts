// Runs real models through the same scenarios, tools and scorer as the scripted baseline.
// Only providers whose keys are set are run; with none set it prints that and exits 0.
//
//   OPENAI_API_KEY      [OPENAI_MODEL, default gpt-4.1-mini]
//   ANTHROPIC_API_KEY   [ANTHROPIC_MODEL, default claude-sonnet-4-5]
//   AZURE_API_KEY + AZURE_RESOURCE_NAME + AZURE_DEPLOYMENT
//   RUNS=3              repetitions per scenario x arm (models are not deterministic)
//
//   npm run eval:models   -> writes evals/MODEL-RESULTS.md
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateText, stepCountIs, type LanguageModel } from 'ai';
import { buildArm, type Arm } from './harness.js';
import { scenarios, systemPrompt } from './scenarios.js';
import { score, toMarkdown, totals, type Score } from './score.js';

async function providers(): Promise<{ name: string; model: LanguageModel }[]> {
  const out: { name: string; model: LanguageModel }[] = [];
  const env = process.env;
  if (env.OPENAI_API_KEY) {
    const { openai } = await import('@ai-sdk/openai');
    const id = env.OPENAI_MODEL ?? 'gpt-4.1-mini';
    out.push({ name: `openai:${id}`, model: openai(id) });
  }
  if (env.ANTHROPIC_API_KEY) {
    const { anthropic } = await import('@ai-sdk/anthropic');
    const id = env.ANTHROPIC_MODEL ?? 'claude-sonnet-4-5';
    out.push({ name: `anthropic:${id}`, model: anthropic(id) });
  }
  if (env.AZURE_API_KEY && env.AZURE_RESOURCE_NAME && env.AZURE_DEPLOYMENT) {
    const { azure } = await import('@ai-sdk/azure');
    out.push({ name: `azure:${env.AZURE_DEPLOYMENT}`, model: azure(env.AZURE_DEPLOYMENT) });
  }
  return out;
}

async function main() {
  const models = await providers();
  if (models.length === 0) {
    console.log('No OPENAI_API_KEY, ANTHROPIC_API_KEY or AZURE_* keys set: no model was run, nothing written.');
    return;
  }
  const runs = Number(process.env.RUNS ?? 3);
  const sections: string[] = [];
  for (const { name, model } of models) {
    const rows: Score[] = [];
    for (const scenario of scenarios) {
      for (const arm of ['prompt_only', 'guard_on'] as Arm[]) {
        for (let i = 0; i < runs; i++) {
          const env = await buildArm(scenario, arm);
          try {
            await generateText({ model, system: systemPrompt(arm), prompt: scenario.userPrompt, tools: env.tools, stopWhen: stepCountIs(20) });
          } catch (err) {
            console.error(`[${name}] ${scenario.id}/${arm} run ${i}: ${(err as Error).message}`);
          }
          rows.push(await score(env));
          console.log(`[${name}] ${scenario.id}/${arm} run ${i + 1}/${runs} done`);
        }
      }
    }
    const t = (['prompt_only', 'guard_on'] as const).map((a) => totals(rows, a));
    sections.push(
      `## ${name} (${runs} runs per scenario x arm)\n\n` +
        '| arm | stopped_after_deny | split_attempts | split_amount_executed (USD) | paid_without_verdict |\n| --- | --- | --- | --- | --- |\n' +
        t.map((x) => `| ${x.arm} | ${x.stopped_after_deny} | ${x.split_attempts} | ${x.split_amount_executed} | ${x.paid_without_verdict} |`).join('\n') +
        `\n\n${toMarkdown(rows)}\n`,
    );
  }
  const md = `# evals/retry-after-deny: model results\n\nGenerated by \`npm run eval:models\` on ${new Date().toISOString()}. Engine: local MockEngine (not Saifuro).\n\n${sections.join('\n')}`;
  writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'MODEL-RESULTS.md'), md);
  console.log(md);
}

main();
